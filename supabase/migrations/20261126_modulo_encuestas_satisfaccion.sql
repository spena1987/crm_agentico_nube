-- 8. Funciones RPC atómicas (SECURITY DEFINER, acceso restringido a service_role)

CREATE OR REPLACE FUNCTION public.adquirir_lote_encuestas_diario(
    p_fecha DATE,
    p_forzar BOOLEAN DEFAULT false
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_claimed BOOLEAN := false;
BEGIN
    INSERT INTO public.encuestas_lotes_diarios (fecha_atencion, estado, claimed_at, finished_at, error_detalle)
    VALUES (p_fecha, 'procesando', now(), NULL, NULL)
    ON CONFLICT (fecha_atencion) DO UPDATE
    SET estado = 'procesando',
        claimed_at = now(),
        finished_at = NULL,
        error_detalle = NULL
    WHERE p_forzar = true
       OR public.encuestas_lotes_diarios.estado = 'fallido'
       OR (
           public.encuestas_lotes_diarios.estado = 'procesando'
           AND public.encuestas_lotes_diarios.claimed_at < now() - interval '15 minutes'
       )
    RETURNING true INTO v_claimed;

    RETURN COALESCE(v_claimed, false);
END;
$$;

CREATE OR REPLACE FUNCTION public.crear_envio_encuesta_con_turnos(
    p_token TEXT,
    p_fecha_atencion DATE,
    p_telefono_e164 TEXT,
    p_expires_at TIMESTAMPTZ,
    p_turnos JSONB
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_envio_id UUID;
    v_is_new BOOLEAN := false;
    v_turnos_count INTEGER := 0;
    v_item JSONB;
BEGIN
    IF p_turnos IS NULL OR jsonb_typeof(p_turnos) <> 'array' OR jsonb_array_length(p_turnos) = 0 THEN
        RETURN NULL;
    END IF;

    SELECT id INTO v_envio_id
    FROM public.encuestas_envios
    WHERE fecha_atencion = p_fecha_atencion
      AND telefono_e164 = p_telefono_e164;

    IF v_envio_id IS NULL THEN
        INSERT INTO public.encuestas_envios (
            token,
            fecha_atencion,
            telefono_e164,
            estado_cola,
            expires_at
        )
        VALUES (
            p_token,
            p_fecha_atencion,
            p_telefono_e164,
            'pendiente',
            p_expires_at
        )
        ON CONFLICT (fecha_atencion, telefono_e164) DO NOTHING
        RETURNING id INTO v_envio_id;

        IF v_envio_id IS NOT NULL THEN
            v_is_new := true;
        ELSE
            SELECT id INTO v_envio_id
            FROM public.encuestas_envios
            WHERE fecha_atencion = p_fecha_atencion
              AND telefono_e164 = p_telefono_e164;
        END IF;
    END IF;

    FOR v_item IN SELECT * FROM jsonb_array_elements(p_turnos)
    LOOP
        INSERT INTO public.encuestas_envios_turnos (
            envio_id,
            turno_id,
            ficha_id,
            unidad_negocio,
            servicio_id,
            servicio_nombre,
            sede_canonica,
            profesional_canonico,
            fecha_turno,
            horario_turno
        )
        VALUES (
            v_envio_id,
            (v_item->>'turno_id')::BIGINT,
            NULLIF(v_item->>'ficha_id', '')::BIGINT,
            COALESCE(NULLIF(v_item->>'unidad_negocio', ''), 'consultas'),
            (v_item->>'servicio_id')::INTEGER,
            v_item->>'servicio_nombre',
            v_item->>'sede_canonica',
            v_item->>'profesional_canonico',
            (v_item->>'fecha_turno')::DATE,
            v_item->>'horario_turno'
        )
        ON CONFLICT (turno_id) DO NOTHING;
    END LOOP;

    SELECT COUNT(*) INTO v_turnos_count
    FROM public.encuestas_envios_turnos
    WHERE envio_id = v_envio_id;

    IF v_turnos_count = 0 AND v_is_new THEN
        DELETE FROM public.encuestas_envios WHERE id = v_envio_id;
        RETURN NULL;
    END IF;

    RETURN v_envio_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_encuestas_envios_pendientes(
    p_limit INTEGER
)
RETURNS SETOF public.encuestas_envios
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    -- Rescatar filas huérfanas atrapadas en 'enviando' por más de 10 minutos
    UPDATE public.encuestas_envios
    SET estado_cola = CASE WHEN intentos >= 3 THEN 'fallido' ELSE 'pendiente' END,
        claimed_at = NULL,
        wa_status = CASE WHEN intentos >= 3 THEN 'failed' ELSE wa_status END,
        wa_error_message = CASE
            WHEN intentos >= 3 THEN COALESCE(wa_error_message, 'Excedido límite de reintentos tras expiración de reserva')
            ELSE wa_error_message
        END
    WHERE estado_cola = 'enviando'
      AND claimed_at < now() - interval '10 minutes';

    RETURN QUERY
    WITH candidatos AS (
        SELECT id
        FROM public.encuestas_envios
        WHERE estado_cola = 'pendiente'
        ORDER BY fecha_atencion ASC, created_at ASC
        LIMIT GREATEST(COALESCE(p_limit, 0), 0)
        FOR UPDATE SKIP LOCKED
    )
    UPDATE public.encuestas_envios e
    SET estado_cola = 'enviando',
        claimed_at = now()
    FROM candidatos c
    WHERE e.id = c.id
    RETURNING e.*;
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_clic_encuesta_turno(
    p_token TEXT,
    p_turno_id BIGINT
)
RETURNS TABLE (ok BOOLEAN, estado TEXT, click_count INTEGER)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_envio_id UUID;
    v_expires_at TIMESTAMPTZ;
    v_new_count INTEGER;
BEGIN
    SELECT id, expires_at
    INTO v_envio_id, v_expires_at
    FROM public.encuestas_envios
    WHERE token = p_token;

    IF v_envio_id IS NULL THEN
        RETURN QUERY SELECT false, 'no_encontrado'::TEXT, 0;
        RETURN;
    END IF;

    IF v_expires_at <= now() THEN
        RETURN QUERY SELECT false, 'expirado'::TEXT, 0;
        RETURN;
    END IF;

    UPDATE public.encuestas_envios_turnos t
    SET click_count = t.click_count + 1,
        clicked_at = COALESCE(t.clicked_at, now())
    WHERE t.envio_id = v_envio_id
      AND t.turno_id = p_turno_id
    RETURNING t.click_count INTO v_new_count;

    IF v_new_count IS NULL THEN
        RETURN QUERY SELECT false, 'turno_invalido'::TEXT, 0;
        RETURN;
    END IF;

    RETURN QUERY SELECT true, 'ok'::TEXT, v_new_count;
END;
$$;

