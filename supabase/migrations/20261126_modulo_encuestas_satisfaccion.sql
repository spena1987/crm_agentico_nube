-- 2. Tabla de control diario de lotes (Fase 1)
CREATE TABLE IF NOT EXISTS public.encuestas_lotes_diarios (
    fecha_atencion DATE PRIMARY KEY,
    estado TEXT NOT NULL CHECK (estado IN ('procesando', 'completado', 'fallido')),
    claimed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ NULL,
    resumen JSONB NULL,
    error_detalle TEXT NULL
);

-- 3. Catálogo de mapeo manual y exclusiones de Geclisa
CREATE TABLE IF NOT EXISTS public.encuestas_mapeo_geclisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_entidad TEXT NOT NULL CHECK (tipo_entidad IN ('servicio', 'prestador', 'sede')),
    geclisa_id TEXT NOT NULL,
    geclisa_nombre_raw TEXT NOT NULL,
    unidad_negocio TEXT NOT NULL DEFAULT 'excluido' CHECK (unidad_negocio IN ('consultas', 'estudios', 'excluido')),
    nombre_canonico TEXT NOT NULL,
    incluir_en_envio BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_encuestas_mapeo_tipo_id UNIQUE (tipo_entidad, geclisa_id)
);

-- 4. Cabecera de envíos diarios agrupados por (fecha_atencion, telefono_e164)
CREATE TABLE IF NOT EXISTS public.encuestas_envios (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    token TEXT NOT NULL UNIQUE,
    fecha_atencion DATE NOT NULL,
    telefono_e164 TEXT NOT NULL,
    estado_cola TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado_cola IN ('pendiente', 'enviando', 'enviado', 'fallido')),
    intentos INTEGER NOT NULL DEFAULT 0,
    claimed_at TIMESTAMPTZ NULL,
    wamid TEXT NULL,
    wa_status TEXT NULL CHECK (wa_status IN ('sent', 'delivered', 'read', 'failed')),
    wa_error_code INTEGER NULL,
    wa_error_message TEXT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    sent_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_encuestas_envios_fecha_tel UNIQUE (fecha_atencion, telefono_e164)
);

CREATE INDEX IF NOT EXISTS idx_encuestas_envios_cola
    ON public.encuestas_envios (estado_cola, fecha_atencion, created_at);

CREATE UNIQUE INDEX IF NOT EXISTS idx_encuestas_envios_wamid
    ON public.encuestas_envios (wamid)
    WHERE wamid IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_encuestas_envios_tel_created
    ON public.encuestas_envios (telefono_e164, created_at DESC);

-- 5. Detalle de turnos incluidos en cada envío (ficha_id por turno, sin PII pública)
CREATE TABLE IF NOT EXISTS public.encuestas_envios_turnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    envio_id UUID NOT NULL REFERENCES public.encuestas_envios(id) ON DELETE CASCADE,
    turno_id BIGINT NOT NULL UNIQUE,
    ficha_id BIGINT NULL,
    unidad_negocio TEXT NOT NULL DEFAULT 'consultas',
    servicio_id INTEGER NOT NULL,
    servicio_nombre TEXT NOT NULL,
    sede_canonica TEXT NOT NULL,
    profesional_canonico TEXT NOT NULL,
    fecha_turno DATE NOT NULL,
    horario_turno TEXT NOT NULL,
    clicked_at TIMESTAMPTZ NULL,
    click_count INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_encuestas_envios_turnos_envio_id
    ON public.encuestas_envios_turnos (envio_id);

-- 6. Lista de bajas (opt-out) exclusiva de encuestas (aislada de estudios_oftalmo)
CREATE TABLE IF NOT EXISTS public.encuestas_opt_out (
